import { test } from 'deepspace/testing'
import { expect } from '@playwright/test'

const heading = (name: string) => ({ name, exact: true })

test('dashboard prioritizes the three tasks and supports real pointer dismissal', async ({ users }) => {
  const [reviewer] = await users(['Dashboard Reviewer'], { force: true })
  await reviewer.page.goto('/home')
  await expect(reviewer.page.getByRole('heading', { name: /Good (morning|afternoon|evening), Dashboard/ })).toBeVisible()
  await expect(reviewer.page.getByRole('heading', { name: /Requests for you/ })).toBeVisible()
  await expect(reviewer.page.getByRole('heading', heading('Your week'))).toBeVisible()
  await expect(reviewer.page.getByRole('heading', heading('People you may connect with'))).toBeVisible()

  await reviewer.page.getByRole('button', { name: 'Profile menu' }).click()
  await expect(reviewer.page.getByTestId('nav-user-email')).toContainText('dashboard-demo@deepspace.test')
  await reviewer.page.keyboard.press('Escape')
  await expect(reviewer.page.getByTestId('nav-user-email')).toBeHidden()

  const requests = reviewer.page.locator('#requests')
  await requests.getByRole('button', { name: 'Accept', exact: true }).first().click()
  await expect(requests.getByText('Responded requests (1)')).toBeVisible()
  await expect(reviewer.page.getByRole('status')).toContainText('No meeting or notification was delivered')
  await requests.getByRole('button', { name: 'Decline', exact: true }).first().click()
  await expect(requests.getByText('Responded requests (2)')).toBeVisible()
  await requests.getByRole('button', { name: 'Accept', exact: true }).click()
  await expect(reviewer.page.getByRole('heading', { name: 'You’re all caught up' })).toBeVisible()
  await requests.getByRole('button', { name: 'Find a buddy', exact: true }).click()
  await expect(reviewer.page.getByRole('dialog')).toBeVisible()
  await reviewer.page.keyboard.press('Escape')
  await expect(reviewer.page.getByRole('dialog')).toHaveCount(0)
  await requests.locator('summary').click()
  await expect(requests.locator('.request-status--accepted')).toHaveCount(2)
  await expect(requests.locator('.request-status--declined')).toHaveCount(1)
})

test('mobile navigation, notifications, and keyboard search work without overflow', async ({ users }) => {
  const [reviewer] = await users(['Dashboard Reviewer'], { force: true })
  await reviewer.page.setViewportSize({ width: 390, height: 844 })
  await reviewer.page.goto('/home')
  await expect(reviewer.page.getByRole('heading', { name: /Requests for you/ })).toBeVisible()
  await reviewer.page.getByRole('button', { name: 'Open navigation', exact: true }).click()
  await expect(reviewer.page.getByRole('navigation', { name: 'Mobile dashboard navigation' })).toBeVisible()
  await reviewer.page.getByRole('button', { name: 'Notifications, 2 unread', exact: true }).click()
  await expect(reviewer.page.getByRole('heading', heading('Updates for you'))).toBeVisible()
  await reviewer.page.getByRole('button', { name: 'Close notifications' }).click()
  await reviewer.page.getByRole('button', { name: 'Mark all as read' }).click()
  await expect(reviewer.page.getByRole('button', { name: 'Notifications', exact: true })).toBeVisible()
  await expect(reviewer.page.getByRole('button', { name: 'Mark all as read' })).toHaveCount(0)
  await reviewer.page.keyboard.press('Control+k')
  await expect(reviewer.page.getByRole('dialog')).toBeVisible()
  await reviewer.page.keyboard.press('Escape')
  await expect(reviewer.page.getByRole('dialog')).toHaveCount(0)
  expect(await reviewer.page.evaluate(() => document.documentElement.scrollWidth)).toBe(390)
})

test('recommendations, first-time setup, and retry preserve honest local state', async ({ users }) => {
  const [reviewer] = await users(['Dashboard Reviewer'], { force: true })
  await reviewer.page.goto('/home')
  const people = reviewer.page.getByRole('region', { name: 'Preview recommendations' })
  await people.locator('.person-match').filter({ hasText: 'Maya Chen' }).getByRole('button', { name: 'View profile' }).click()
  await expect(reviewer.page.getByRole('dialog')).toContainText('Example profile')
  await reviewer.page.keyboard.press('Escape')
  await people.locator('.person-match').filter({ hasText: 'Maya Chen' }).getByRole('button', { name: 'Connect', exact: true }).click()
  await expect(people.getByRole('button', { name: 'Preview invited', exact: true })).toBeDisabled()
  await people.getByRole('button', { name: 'Send request', exact: true }).click()
  await expect(people.getByRole('button', { name: 'Exchange preview saved', exact: true })).toBeDisabled()
  await expect(people.getByRole('button', { name: 'Preview invited', exact: true })).toBeDisabled()

  await reviewer.page.getByLabel('Workspace preview mode').selectOption('empty')
  await expect(reviewer.page.getByRole('heading', heading('Make your profile a starting point'))).toBeVisible()
  await expect(reviewer.page.getByRole('heading', { name: /Requests for you/ })).toHaveCount(0)
  await reviewer.page.getByRole('button', { name: 'Complete profile' }).click()
  await reviewer.page.getByLabel('Program and year').fill('Computer Science, Second year')
  await reviewer.page.getByRole('button', { name: 'Save preview profile' }).click()
  await expect(reviewer.page.locator('#profile-summary')).toContainText('Computer Science · Second year')
  const editor = reviewer.page.locator('#profile-summary form')
  await expect(editor).toHaveCount(0)
  await reviewer.page.getByRole('button', { name: 'Preview error/recovery state' }).click()
  await expect(reviewer.page.getByRole('alert')).toContainText('Try again')
  await reviewer.page.getByRole('button', { name: 'Retry', exact: true }).click()
  await expect(reviewer.page.getByRole('heading', heading('Make your profile a starting point'))).toBeVisible()
})
